import { Injectable } from '@nestjs/common';
import { connectDB,sql } from '../config/db';
@Injectable()
export class RegisterRepository {
    //---------------------USER REGISTRATION GET---------------------------
 async userRegistrationget() {
try {
// Establish database connection
const pool = await connectDB();
    // Execute stored procedure
    const result = await pool
      .request()
      .execute('USP_User_Registration_Get');
    // Check whether stored procedure returned data
    if (
      !result.recordset ||
      result.recordset.length === 0 ||
      !result.recordset[0].Result
    ) {
      throw new Error(
        'No result returned from USP_User_Registration_Get',
      );
    }
    // Parse JSON returned by the stored procedure
    const response = JSON.parse(result.recordset[0].Result);
    // Return the parsed response
    return response;
  } catch (error) {
    // Log actual database error
    console.error(
      'Error executing USP_User_Registration_Get:',
      error,
    );
    // Pass error to service
    throw error;
  }
}   
  //---------------------USER REGISTRATION PRE-CHECK---------------------------
  /**
   * Executes the pre-registration stored procedure.
   * The stored procedure returns one JSON column.
   * Since the column name is generated by SQL Server,
   * the first column is read by ordinal position.
   */
  async registrationCheck(
    umail: string,
    mobileContCode: string,
  ): Promise<string | null> {
    try {
      // Establish database connection.
      const pool = await connectDB();
      // Execute the pre-registration stored procedure.
      const result = await pool
        .request()
        .input(
          'umail',
          sql.VarChar(254),
          umail,
        )
        .input(
          'mobile_cont_code',
          sql.VarChar(25),
          mobileContCode,
        )
        .execute(
          'dbo.USP_User_Registration_Mobile_Mail_Check',
        );
      // Check whether the stored procedure returned data.
      if (
        !result.recordset ||
        result.recordset.length === 0
      ) {
        return null;
      }
      /**
       * Read the first column from every returned row.
       * Concatenate the values in case the JSON response
       * is split across multiple rows.
       */
      const response = result.recordset
        .map((row) => Object.values(row)[0])
        .filter(
          (value): value is string =>
            typeof value === 'string',
        )
        .join('');
      return response || null;
    } catch (error) {
      // Log the database error for server-side troubleshooting.
      console.error(
        'Error executing USP_User_Registration_Mobile_Mail_Check:',
        error,
      );
      // Pass the error to the service layer.
      throw error;
    }
  }
}